package com.mycompany.myshop.backend.benchmark;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Collects what {@link Theme2Baseline} measured and renders it as markdown.
 *
 * <p>Deliberately dumb: it holds rows and prints them. Keeping the rendering here rather than in the
 * measurement class is what lets the after-run produce a file the before-run's file can be diffed
 * against — same columns, same order, same units.
 */
final class BenchmarkReport {

    /**
     * One measured operation.
     *
     * @param capability     the row of the plan's capability table this belongs to
     * @param operation      what the application actually did, in its own vocabulary
     * @param millis         wall time
     * @param rows           rows the database returned or wrote
     * @param domainObjects  domain objects constructed on the way to the response — see
     *                       {@link Theme2Baseline} for how the per-row constants are derived
     * @param statements     JDBC statements prepared, counted by Hibernate rather than estimated
     * @param retainedHeapMb heap the returned value still holds once the operation is over, to the
     *                       nearest MB. Approximate, and deliberately not "heap allocated": the
     *                       gap between this and the domain-object count is the point — the
     *                       objects were built and then thrown away.
     */
    record Row(String capability, String operation, long millis, long rows,
               long domainObjects, long statements, long retainedHeapMb) { }

    private final List<Row> rows = new ArrayList<>();
    private final Map<String, String> plans = new LinkedHashMap<>();
    private final List<String> facts = new ArrayList<>();

    void add(Row row) {
        rows.add(row);
    }

    void addPlan(String label, String plan) {
        plans.put(label, plan);
    }

    void addFact(String fact) {
        facts.add(fact);
    }

    String render() {
        var out = new StringBuilder();
        out.append("# Theme 2 — baseline measurements\n\n");
        out.append("Generated by `./gradlew benchmark` in `system/multitier/backend-clean-java`, ")
           .append("over `system/db/seed/demo-volume.sql`.\n\n");

        out.append("## Seed\n\n");
        for (var fact : facts) {
            out.append("- ").append(fact).append('\n');
        }

        out.append("\n## What the application does today\n\n");
        out.append("| Capability | Operation | Wall ms | Rows | Domain objects | JDBC statements | Retained heap MB |\n");
        out.append("|---|---|---:|---:|---:|---:|---:|\n");
        for (var row : rows) {
            out.append("| ").append(row.capability())
               .append(" | ").append(row.operation())
               .append(" | ").append(row.millis())
               .append(" | ").append(row.rows())
               .append(" | ").append(row.domainObjects())
               .append(" | ").append(row.statements())
               .append(" | ").append(row.retainedHeapMb())
               .append(" |\n");
        }

        out.append("\n## Query plans\n\n");
        for (var plan : plans.entrySet()) {
            out.append("### ").append(plan.getKey()).append("\n\n```\n")
               .append(plan.getValue()).append("\n```\n\n");
        }
        return out.toString();
    }

    void writeTo(Path path) {
        try {
            Files.createDirectories(path.getParent());
            Files.writeString(path, render());
        } catch (IOException e) {
            throw new UncheckedIOException("Could not write the benchmark report to " + path, e);
        }
    }
}
